"""Table III column PANKTI_STATUS: the paper, the authors' published tests run in this environment, and the tests
generated by this reproduction.

usage: table3_status.py <authors_pankti_status.csv> <ours_pankti_status.csv> <out_prefix>

The inputs are outputs of pankti_status.py (with --table3 and --control). Rows are the 46 methods of Table III, plus
any method only this reproduction invoked. Writes <out_prefix>.csv and <out_prefix>.txt.
"""
import csv
import sys


def load(path):
    with open(path, newline="", encoding="utf-8") as f:
        return {(r["class"], r["method"], r["params"]): r for r in csv.DictReader(f)}


def main(argv):
    if len(argv) != 4:
        print(__doc__)
        return 2
    authors, ours = load(argv[1]), load(argv[2])
    rows = []
    for key in sorted(set(authors) | set(ours), key=lambda k: (int((ours.get(k) or authors[k])["row"] or 999), k)):
        a, o = authors.get(key, {}), ours.get(key, {})
        rows.append({
            "row": (o or a)["row"], "class": key[0], "method": key[1], "params": key[2],
            "paper_status": (o or a)["paper_status"],
            "authors_after_here": a.get("after", ""), "authors_status_here": a.get("pankti_status", ""),
            "ours_after": o.get("after", ""), "ours_status": o.get("pankti_status", ""),
            "control_without_generated_tests": (o or a).get("control", ""),
            "ours_detected": o.get("detected_after", ""), "ours_not_detected": o.get("not_detected_after", ""),
        })
    with open(f"{argv[3]}.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)

    in_paper = [r for r in rows if r["paper_status"]]
    lines = [f"Table III methods: {len(in_paper)}"]
    for label, col in (("paper", "paper_status"), ("authors' tests, run here", "authors_status_here"),
                       ("this reproduction", "ours_status")):
        well = sum(1 for r in in_paper if r[col] == "well-tested")
        lines.append(f"  {label}: well-tested {well} / {len(in_paper)}")
    for label, col in (("authors' tests, run here", "authors_status_here"), ("this reproduction", "ours_status")):
        lines.append(f"  same status as the paper ({label}): "
                     f"{sum(1 for r in in_paper if r[col] == r['paper_status'])} / {len(in_paper)}")
    same_cls = sum(1 for r in in_paper if r["authors_after_here"] == r["ours_after"])
    lines.append(f"  same Descartes classification after, authors' tests vs ours: {same_cls} / {len(in_paper)}")
    lines += [f"  not in Table III: {r['class'].rsplit('.', 1)[1]}.{r['method']}: {r['ours_after']}"
              for r in rows if not r["paper_status"]]
    text = "\n".join(lines) + "\n"
    with open(f"{argv[3]}.txt", "w", newline="\n", encoding="utf-8") as f:
        f.write(text)
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
