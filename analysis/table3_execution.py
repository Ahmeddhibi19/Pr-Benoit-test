"""Table III columns #PANKTI_TESTS, #PASSING and #FAILING: the paper, the authors' published tests run in this
environment, and the tests generated by this reproduction.

usage: table3_execution.py <authors_test_outcomes.csv> <ours_test_outcomes.csv> <out_prefix>

The inputs are outputs of test_outcomes.py (with --generated and --table3). Rows are the 46 methods of Table III,
plus any method only this reproduction invoked. Writes <out_prefix>.csv and <out_prefix>.txt.
"""
import csv
import sys
from pathlib import Path


def load(path):
    with open(path, newline="", encoding="utf-8") as f:
        return {(r["class"], r["method"], r["params"]): r for r in csv.DictReader(f)}


def main(argv):
    if len(argv) < 4:
        print(__doc__)
        return 2
    authors, ours, out = load(argv[1]), load(argv[2]), Path(argv[3])
    keys = sorted(set(authors) | set(ours), key=lambda k: int((authors.get(k) or ours.get(k))["row"] or 999))
    rows = []
    for k in keys:
        a, o = authors.get(k, {}), ours.get(k, {})
        ref = a or o
        rows.append({
            "row": ref.get("row", ""), "class": k[0], "method": k[1], "params": k[2],
            "paper_tests": (int(ref["paper_passing"]) + int(ref["paper_failing"])) if ref.get("paper_passing") else "",
            "paper_passing": ref.get("paper_passing", ""), "paper_failing": ref.get("paper_failing", ""),
            "authors_tests_here": a.get("executed", ""), "authors_passing_here": a.get("passing", ""),
            "authors_failing_here": a.get("failing", ""), "authors_flaky_here": a.get("flaky", ""),
            "ours_tests": o.get("executed", ""), "ours_passing": o.get("passing", ""), "ours_failing": o.get("failing", ""),
            "ours_flaky": o.get("flaky", "")})
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(f"{out}.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)

    def total(col):
        return sum(int(r[col]) for r in rows if r[col] != "")

    paper_rows = [r for r in rows if r["paper_passing"] != ""]
    same_authors = sum(1 for r in paper_rows if (r["authors_passing_here"], r["authors_failing_here"])
                       == (r["paper_passing"], r["paper_failing"]))
    same_ours = sum(1 for r in paper_rows if (r["ours_passing"], r["ours_failing"]) == (r["paper_passing"], r["paper_failing"]))
    lines = [
        f"{'':<44}{'tests':>9}{'passing':>10}{'failing':>10}{'flaky':>8}{'pass rate':>11}",
        f"{'paper (Table III)':<44}{total('paper_tests'):>9,}{total('paper_passing'):>10,}{total('paper_failing'):>10,}"
        f"{'':>8}{total('paper_passing') / total('paper_tests'):>11.2%}",
        f"{'authors published tests, run here 5 times':<44}{total('authors_tests_here'):>9,}"
        f"{total('authors_passing_here'):>10,}{total('authors_failing_here'):>10,}{total('authors_flaky_here'):>8,}"
        f"{total('authors_passing_here') / total('authors_tests_here'):>11.2%}",
        f"{'this reproduction, run 5 times':<44}{total('ours_tests'):>9,}{total('ours_passing'):>10,}"
        f"{total('ours_failing'):>10,}{total('ours_flaky'):>8,}{total('ours_passing') / total('ours_tests'):>11.2%}",
        "",
        f"Table III rows with the paper's #PASSING and #FAILING: authors' tests run here {same_authors} / {len(paper_rows)}, "
        f"this reproduction {same_ours} / {len(paper_rows)}",
    ]
    lines += [f"  row {r['row']:>2} {r['class'].rsplit('.', 1)[1]}.{r['method']}: paper {r['paper_passing']} / {r['paper_failing']}, "
              f"ours {r['ours_passing']} / {r['ours_failing']} of {r['ours_tests']}"
              for r in paper_rows if (r["ours_passing"], r["ours_failing"]) != (r["paper_passing"], r["paper_failing"])]
    extra = [r for r in rows if r["paper_passing"] == ""]
    lines += [f"  not in Table III: {r['class'].rsplit('.', 1)[1]}.{r['method']}: ours {r['ours_passing']} / {r['ours_failing']} "
              f"of {r['ours_tests']}" for r in extra]
    text = "\n".join(lines) + "\n"
    Path(f"{out}.txt").write_text(text, encoding="utf-8", newline="\n")
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
